import argparse
import json
from collections import Counter
from pathlib import Path


def load_rows(path: Path):
    with path.open("r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            yield json.loads(line)


def main():
    parser = argparse.ArgumentParser(description="Lightweight quality summary for generated JSONL.")
    parser.add_argument("--data", type=Path, required=True, help="Path to JSONL generated by generate_dataset.py")
    args = parser.parse_args()

    total = 0
    passed = 0
    difficulties = Counter()
    subjects = Counter()
    notes = Counter()

    for row in load_rows(args.data):
        total += 1
        diff = row.get("difficulty", "unknown")
        subj = row.get("subject", "unknown")
        difficulties[diff] += 1
        subjects[subj] += 1
        quality = row.get("quality") or {}
        if quality.get("passed"):
            passed += 1
        note = (quality.get("notes") or "none").strip().lower()
        notes[note] += 1

    print(f"Total: {total}")
    print(f"Passed: {passed} ({(passed/total*100):.1f}%)" if total else "Passed: 0")
    print("By difficulty:", dict(difficulties))
    print("By subject:", dict(subjects))
    top_notes = notes.most_common(5)
    print("Top notes:", top_notes)


if __name__ == "__main__":
    main()
